#!/usr/bin/env bash
# Generate the real-matched training + validation sets in one go.
#
#   nohup bash run_realmatch_data.sh > gen_realmatch.log 2>&1 &     # full run
#   SMOKE=1 bash run_realmatch_data.sh                              # ~1 min check into data_realmatch_smoke
#
# Output (relative to this directory):
#   data_realmatch_200k/train/{images,labels/labels.jsonl}   TRAIN_TOTAL samples (default 200000)
#   data_realmatch_200k/val/{images,labels/labels.jsonl}     VAL_TOTAL   samples (default 1000)
# train.py derives the val set by replacing "train" with "val" in --image_dir/--label_path, so only
# the data paths in train_realmatch.sh need pointing at data_realmatch_200k.
#
# What is different from generate_balanced_shuffled.sh (details: src/realstats/README.md):
#   * braille_gen_fineweb_v2.py with --real_profile: scale, tightness, cell/word spacing, dot size,
#     lines per image follow measured real photos. The original generator is untouched.
#   * profile = configs/realmatch_profile_v1_noeval.json (built WITHOUT the test images; its output
#     matches the full profile). Use REAL_PROFILE=configs/realmatch_profile_v1.json to include them.
#   * per-bucket text length caps 16/48/16/120 chars (real crops are short; original 120/180/120/450).
#     Reset with G1_SHORT_MAX_CHARS=120 G1_MID_MAX_CHARS=180 G2_SHORT_MAX_CHARS=120 G2_LONG_MAX_CHARS=450.
#   * bucket mix 35% g1 1-2 words, 15% g1 3-6, 20% g2 1-3, 30% g2 4-50 (was 40/10/20/30 with
#     6-10 and 6-50, which produced no 4-5 word texts; real eval has 12.5% of them). Measured mix
#     (FineWeb preview): 1w 26%, 2w 23%, 3w 10%, 4-5w 10%, 6-9w 10%, 10-15w 8%, 16+ 13%.
#   * STRIP_PUNCT_TOKENS=1: no punctuation-only texts, no leading/trailing "-" tokens (2.7% of texts
#     before; the real eval has none, and the last model learned to emit "- am").
#   * train-only word/char shuffling (10% / 15%); the val set is not shuffled.
#   * generator (2026-10-04 evening): no clipped dots (every margin >= 0.08 cell around a padded ink box)
#     and a cell-pitch floor for longer texts (>=16 cells: 18 px, >=32 cells: 22 px).
#   * new seeds (train 3337, val 9337) so the text windows differ from the earlier 50k data_realmatch.
# Runtime: rendering ~40 min for 200k at WORKERS=32 (extrapolated from a 400-sample timing) plus
# FineWeb streaming per bucket. Disk: ~6-8 GB for 200k (estimate; long samples are larger now).
#
# Do not edit this file or generate_realmatch.sh while a run is in progress.
set -euo pipefail
cd "$(dirname "$0")"

if [[ "${SMOKE:-0}" == 1 ]]; then
  TRAIN_TOTAL="${TRAIN_TOTAL:-200}"; VAL_TOTAL="${VAL_TOTAL:-100}"
  DATA_ROOT="${DATA_ROOT:-data_realmatch_smoke}"; WORKERS="${WORKERS:-8}"
else
  TRAIN_TOTAL="${TRAIN_TOTAL:-200000}"; VAL_TOTAL="${VAL_TOTAL:-1000}"
  DATA_ROOT="${DATA_ROOT:-data_realmatch_200k}"; WORKERS="${WORKERS:-32}"
fi
export DATA_ROOT WORKERS
export PYTHON="${PYTHON:-python}"
export REAL_PROFILE="${REAL_PROFILE:-configs/realmatch_profile_v1_noeval.json}"
export G1_SHORT_MAX_CHARS="${G1_SHORT_MAX_CHARS:-16}"
export G1_MID_MAX_CHARS="${G1_MID_MAX_CHARS:-48}"
export G2_SHORT_MAX_CHARS="${G2_SHORT_MAX_CHARS:-16}"
export G2_LONG_MAX_CHARS="${G2_LONG_MAX_CHARS:-120}"
export G1_SHORT_PCT="${G1_SHORT_PCT:-35}" G1_MID_PCT="${G1_MID_PCT:-15}"
export G2_SHORT_PCT="${G2_SHORT_PCT:-20}" G2_LONG_PCT="${G2_LONG_PCT:-30}"
export G1_SHORT_WORDS="${G1_SHORT_WORDS:-1-2}" G1_MID_WORDS="${G1_MID_WORDS:-3-6}"
export G2_SHORT_WORDS="${G2_SHORT_WORDS:-1-3}" G2_LONG_WORDS="${G2_LONG_WORDS:-4-50}"
export STRIP_PUNCT_TOKENS="${STRIP_PUNCT_TOKENS:-1}"

# the generator needs liblouis (UEB grade 1/2). Without it it silently falls back to a small
# built-in translator and the grade-2 labels would differ from your previous data.
if ! "$PYTHON" -c "import louis, cv2, datasets, tqdm" 2>/dev/null; then
  if [[ -f src/realstats/louis_env.sh ]]; then
    # shellcheck disable=SC1091
    source src/realstats/louis_env.sh   # in-repo liblouis build
  fi
  if ! "$PYTHON" -c "import louis, cv2, datasets, tqdm" 2>/dev/null; then
    echo "PYTHON='$PYTHON' cannot import louis/cv2/datasets/tqdm. Point PYTHON at your braille env, e.g." >&2
    echo "  PYTHON=/path/to/braille-env/bin/python bash run_realmatch_data.sh" >&2
    exit 1
  fi
fi

for split in train val; do
  if [[ -e "$DATA_ROOT/$split" ]]; then
    echo "$DATA_ROOT/$split already exists; choose another DATA_ROOT (nothing was generated)." >&2
    exit 1
  fi
done

echo "== real-matched data -> $DATA_ROOT  (train $TRAIN_TOTAL, val $VAL_TOTAL, profile $REAL_PROFILE)"
echo "== buckets (pct, words, max chars): g1 $G1_SHORT_PCT% $G1_SHORT_WORDS $G1_SHORT_MAX_CHARS | g1 $G1_MID_PCT% $G1_MID_WORDS $G1_MID_MAX_CHARS | g2 $G2_SHORT_PCT% $G2_SHORT_WORDS $G2_SHORT_MAX_CHARS | g2 $G2_LONG_PCT% $G2_LONG_WORDS $G2_LONG_MAX_CHARS | strip punct tokens: $STRIP_PUNCT_TOKENS"

SPLIT=val   TOTAL="$VAL_TOTAL"   SEED_BASE="${VAL_SEED_BASE:-9337}"   bash generate_realmatch.sh
SPLIT=train TOTAL="$TRAIN_TOTAL" SEED_BASE="${TRAIN_SEED_BASE:-3337}" bash generate_realmatch.sh

for split in train val; do
  n_img=$(find "$DATA_ROOT/$split/images" -type f | wc -l)
  n_lab=$(wc -l < "$DATA_ROOT/$split/labels/labels.jsonl")
  echo "== $split: $n_img images, $n_lab labels"
  if [[ "$n_img" != "$n_lab" ]]; then echo "image/label count mismatch in $split" >&2; exit 1; fi
done
echo "== done. Train with: bash train_realmatch_200k.sh   (expects $DATA_ROOT/train)"
